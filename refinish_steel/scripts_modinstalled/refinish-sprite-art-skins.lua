-- refinish-sprite-art-skins.lua
-- =====================================================================
-- HIDES, COMPLETE
-- =====================================================================
-- Every filled cell of the vanilla HIDES page, copied pixel for
-- pixel and retoned onto the neutral ramp so any of them can be tinted.
-- 24 of 24 cells carry art; the empty ones are skipped rather than
-- registered blank.
--
-- Named skins_<x>_<y> after the cell, not after what vanilla uses it
-- for, because a cell often serves several tokens and the coordinate is
-- the thing that stays true. The comment above each names the vanilla
-- users where the raws declare any.
--
-- Retoned by RANK, spread proportionally across the nine neutral steps
-- as round(i * 8 / (n - 1)), because source cells carry anywhere from a
-- handful of values to eighteen. Relative shading survives; absolute
-- values do not, which is the point. Untinted these look like pale grey
-- rubble, and the colour is supposed to arrive from the material.
-- =====================================================================

